/* Model Lifecycle Watch — client app.
   Loads data/models.json (generated by pipeline/fetch_parse.py), renders
   per-model status cards with search + status/vendor filters. No backend,
   no uploads, no tracking. */

const DATA_BASE = "data/";

let allModels = [];
let statusFilter = "all";
let vendorFilter = { Anthropic: true, OpenAI: true, DeepSeek: true };
let searchQuery = "";

const STATUS_LABEL = { active: "Active", deprecated: "Deprecated", retired: "Retired" };

function fmtDate(iso) {
  if (!iso) return "—";
  const d = new Date(iso + "T00:00:00Z");
  if (isNaN(d)) return iso;
  return d.toLocaleDateString(undefined, { year: "numeric", month: "short", day: "numeric" });
}

function daysUntil(iso) {
  if (!iso) return null;
  const t = new Date(iso + "T00:00:00Z");
  const now = new Date();
  return Math.ceil((t - now) / 86400000);
}

function statusClass(m) {
  // A deprecated model whose retirement is imminent shows as deprecated (yellow).
  return m.status;
}

function renderCard(m) {
  const card = document.createElement("div");
  card.className = "card";

  const top = document.createElement("div");
  top.className = "top";

  const h3 = document.createElement("h3");
  h3.textContent = m.model_id;
  top.appendChild(h3);

  const vendor = document.createElement("span");
  vendor.className = "vendor";
  vendor.textContent = m.vendor;
  top.appendChild(vendor);

  const badge = document.createElement("span");
  badge.className = "badge " + statusClass(m);
  badge.textContent = STATUS_LABEL[m.status] || m.status;
  top.appendChild(badge);

  card.appendChild(top);

  const rows = document.createElement("div");
  rows.className = "rows";

  if (m.status === "deprecated" && m.retirement) {
    const d = daysUntil(m.retirement);
    const row = document.createElement("div");
    row.className = "row";
    row.innerHTML = `<span class="label">Shuts down</span><span class="val soon"><strong>${fmtDate(m.retirement)}</strong>${d !== null ? ` (${d <= 0 ? "now" : d + " days"})` : ""}</span>`;
    rows.appendChild(row);
  } else if (m.status === "retired" && m.retirement) {
    const row = document.createElement("div");
    row.className = "row";
    row.innerHTML = `<span class="label">Retired</span><span class="val">${fmtDate(m.retirement)}</span>`;
    rows.appendChild(row);
  }

  if (m.status === "active" && m.retirement_not_before) {
    const d = daysUntil(m.retirement_not_before);
    const row = document.createElement("div");
    row.className = "row";
    row.innerHTML = `<span class="label">Guaranteed</span><span class="val">available until at least ${fmtDate(m.retirement_not_before)}${d !== null ? ` (${d} days)` : ""}</span>`;
    rows.appendChild(row);
  }

  if (m.announced) {
    const row = document.createElement("div");
    row.className = "row";
    row.innerHTML = `<span class="label">Announced</span><span class="val">${fmtDate(m.announced)}</span>`;
    rows.appendChild(row);
  }

  if (m.replacement) {
    const row = document.createElement("div");
    row.className = "row";
    row.innerHTML = `<span class="label">Replace with</span><span class="val replacement"><strong>${escapeHtml(m.replacement)}</strong></span>`;
    rows.appendChild(row);
  }

  if (m.note) {
    const row = document.createElement("div");
    row.className = "note";
    row.textContent = m.note;
    rows.appendChild(row);
  }

  card.appendChild(rows);

  const src = document.createElement("div");
  src.className = "src";
  src.innerHTML = `Source: <a href="${escapeHtml(m.source_url)}" target="_blank" rel="noopener">${escapeHtml(new URL(m.source_url).hostname)}</a> · as of ${fmtDate(m.as_of)}`;
  card.appendChild(src);

  return card;
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  }[c]));
}

function matches(m) {
  if (statusFilter !== "all" && m.status !== statusFilter) return false;
  if (!vendorFilter[m.vendor]) return false;
  if (searchQuery) {
    const hay = (m.model_id + " " + (m.replacement || "") + " " + (m.family || "")).toLowerCase();
    if (!hay.includes(searchQuery)) return false;
  }
  return true;
}

function render() {
  const shown = allModels.filter(matches);
  const countEl = document.getElementById("count");
  countEl.textContent = `${shown.length} of ${allModels.length} models`;

  const cardsEl = document.getElementById("cards");
  cardsEl.innerHTML = "";
  const emptyEl = document.getElementById("empty");
  if (shown.length === 0) {
    emptyEl.classList.remove("hidden");
  } else {
    emptyEl.classList.add("hidden");
    shown.forEach((m) => cardsEl.appendChild(renderCard(m)));
  }
}

function renderSummary() {
  const summary = document.getElementById("summary");
  const counts = { active: 0, deprecated: 0, retired: 0 };
  allModels.forEach((m) => { counts[m.status] = (counts[m.status] || 0) + 1; });
  summary.textContent =
    `${counts.deprecated || 0} deprecated · ${counts.active || 0} active · ${counts.retired || 0} retired`;
}

function renderAsOf() {
  const el = document.getElementById("asof");
  fetch(DATA_BASE + "models.json")
    .then((r) => r.json())
    .then((data) => {
      if (data.generated_at) {
        const g = new Date(data.generated_at);
        const spans = (data.sources || []).map((s) => {
          const cls = s.status === "ok" ? "src-ok" : s.status === "no-deprecation-page" ? "src-gap" : "src-fail";
          const note = s.status === "ok" ? "" : s.status === "no-deprecation-page" ? " (no deprecation page — gap documented)" : " (fetch failed)";
          return `<span class="${cls}">${s.vendor}${note}</span>`;
        }).join(" · ");
        el.innerHTML = `Snapshot ${g.toLocaleString()} · sources: ${spans}`;
      }
    })
    .catch(() => { el.textContent = "Could not load source status."; });
}

function init() {
  document.getElementById("search").addEventListener("input", (e) => {
    searchQuery = e.target.value.trim().toLowerCase();
    render();
  });

  document.querySelectorAll(".filter").forEach((btn) => {
    btn.addEventListener("click", () => {
      document.querySelectorAll(".filter").forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");
      statusFilter = btn.dataset.status;
      render();
    });
  });

  document.querySelectorAll(".vendor").forEach((cb) => {
    cb.addEventListener("change", () => {
      vendorFilter[cb.value] = cb.checked;
      render();
    });
  });

  fetch(DATA_BASE + "models.json")
    .then((r) => {
      if (!r.ok) throw new Error("HTTP " + r.status);
      return r.json();
    })
    .then((data) => {
      allModels = data.models || [];
      renderSummary();
      render();
      renderAsOf();
    })
    .catch((err) => {
      document.getElementById("empty").textContent = "Could not load model data: " + err.message;
      document.getElementById("empty").classList.remove("hidden");
    });
}

document.addEventListener("DOMContentLoaded", init);
